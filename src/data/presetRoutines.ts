const createSets = (count: number, weight: number, reps: number) => {
  return Array.from({ length: count }, (_, i) => ({
    id: `set-${Date.now()}-${i + 1}`,
    setNumber: i + 1,
    weight,
    reps,
    previousBest: {
      weight: Math.round(weight * 0.95),
      reps,
    },
    rpe: i === count - 1 ? 9 : 8,
    isCompleted: false,
    isWarmup: i === 0 && count > 3,
  }));
};

